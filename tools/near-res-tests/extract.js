#!/usr/bin/env node
/*
 * 从 app/src/main/assets/app.js 原样抽取「近家资源点」功能用到的纯逻辑函数，拼成一个独立的 Node 模块
 * （extracted.js），供同目录下的 test_*.js 测试脚本加载。
 *
 * 为什么要抽取而不是直接 require app.js：app.js 以 <script type="module"> 方式跑在浏览器里，顶层会直接
 * 调用 boot()，而 boot() 牵动大量 DOM / Worker / IndexedDB API，在没有浏览器环境的 Node 里没法直接跑。
 * 这里按「文件里每个顶层 function/const 语句的起止行」切片，只把测试需要的那些函数和它们的少量工具函数依
 * 赖原样复制出来——是文件内容的直接切片，不是照着重新敲一遍，保证测的是会被实际打进 APK / exe 的那份代码。
 *
 * 用法：node extract.js   会重新生成 extracted.js；改了 app.js 里这些函数之后重新跑一遍即可。
 */
const fs = require('fs');
const path = require('path');
const APP_JS = path.join(__dirname, '../../app/src/main/assets/app.js');

const src = fs.readFileSync(APP_JS, 'utf-8');
const lines = src.split('\n');
const starts = [];
for (let i = 0; i < lines.length; i++) {
  if (/^(async function |function |const |let )\S/.test(lines[i])) starts.push(i);
}
starts.push(lines.length);
const chunks = {};
for (let idx = 0; idx < starts.length - 1; idx++) {
  const i0 = starts[idx], i1 = starts[idx + 1];
  const line = lines[i0];
  let m = line.match(/^(?:async function|function)\s+([A-Za-z0-9_$]+)\s*\(/);
  if (!m) m = line.match(/^(?:const|let)\s+([A-Za-z0-9_$]+)\s*=/);
  if (m && !(m[1] in chunks)) chunks[m[1]] = [i0, i1];
}

const needed = ['keyOf', 'dist2', 'clamp', 'intOf', 'base64ToBytes', 'bytesToBase64', 'streamTransform', 'gunzip',
  'gzip', 'inflateZlib', 'XML_ENT', 'unescapeXml', 'xmlAttrs', 'parseTilesets', 'itemTileInfo', 'decodeLayerData',
  'findLayerByName', 'readLayerByName', 'resourcePoolGids', 'patchTmxItems', 'NEAR_RES_DEFAULTS', 'NEAR_RES_SEP',
  'NEAR_RES_SPAWN_SEP', 'RESOURCE_FLIPS', 'detectFlip', 'groupSpawnOrbits', 'seededRng', 'hashSeed',
  'isWallBlocking', 'resourceCellValid', 'localReachable', 'pickResourcePoints', 'markItemsOccupied',
  'planNearSpawnResources'];
const missing = needed.filter(n => !(n in chunks));
if (missing.length) { console.error('extract.js: missing functions in app.js:', missing); process.exit(1); }

const out = [
  '// AUTO-GENERATED by extract.js — do not hand-edit. Regenerate with `node extract.js`.',
  "const S = { nearRes: { enabled: true, perSpawn: 2, min: 10, max: 20 } };",
  "function dimsOf(s) { const m = terrainMatrix(s) || getMatrix('id_matrix', s) || getMatrix('wall_matrix', s); if (m?.shape) return [m.shape[0], m.shape[1]]; return [Number(s?.meta?.height) || 0, Number(s?.meta?.width) || 0]; }",
  "function getMatrix(key, s) { return s?.matrices?.[key] || null; }",
  "function terrainMatrix(s) { return getMatrix('height_map', s) || getMatrix('coastline_height_map', s); }"
];
for (const n of needed) { const [i0, i1] = chunks[n]; out.push(lines.slice(i0, i1).join('\n').replace(/\s+$/, '')); }
out.push('module.exports = { keyOf, resourcePoolGids, patchTmxItems, planNearSpawnResources, groupSpawnOrbits, ' +
  'detectFlip, pickResourcePoints, resourceCellValid, localReachable, dimsOf, getMatrix, S, RESOURCE_FLIPS, ' +
  'itemTileInfo, parseTilesets };');

fs.writeFileSync(path.join(__dirname, 'extracted.js'), out.join('\n\n') + '\n');
console.log(`extract.js: wrote extracted.js (${needed.length} functions from app.js)`);
